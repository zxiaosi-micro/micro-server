// apitypes · .api → TS 类型生成器（02 §12.5：自研，唯一保留的自定义生成器；
// goctl 无官方 TS 生成器）。生成物入库 micro-web/packages/shared/types，CI diff 阻断。
//
// 用法：
//
//	go run ./tools/apitypes -api services/admin-bff/api/entry.api -out ../micro-web/packages/shared/types/admin-bff.ts
//	  -api   .api 契约文件（可多个，逗号分隔）
//	  -out   输出 TS 文件（缺省 stdout）
//
// 映射规则：string→string；int*/float*/double→number；bool→boolean；
// []T→T[]；自定义类型→引用生成 interface；标签含 optional/default → 字段可选（?）。
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type field struct {
	Name     string
	Type     string
	Optional bool
}

type apiType struct {
	Name   string
	Fields []field
}

var (
	typeRe     = regexp.MustCompile(`^\s*([A-Z][A-Za-z0-9_]*)\s+(\[\])?([A-Za-z0-9_]+)\s+\x60(.*)\x60\s*(?://.*)?$`)
	typeDeclRe = regexp.MustCompile(`^\s*type\s+([A-Z][A-Za-z0-9_]*)\s*\{\s*$`)
)

func main() {
	apis := flag.String("api", "", ".api 文件（逗号分隔多个）")
	out := flag.String("out", "", "输出 TS 文件（缺省 stdout）")
	flag.Parse()
	if *apis == "" {
		fmt.Fprintln(os.Stderr, "apitypes: -api 必填")
		os.Exit(2)
	}

	types := map[string]apiType{}
	order := []string{}
	for _, f := range strings.Split(*apis, ",") {
		if err := parseFile(strings.TrimSpace(f), types, &order); err != nil {
			fmt.Fprintf(os.Stderr, "apitypes: %v\n", err)
			os.Exit(1)
		}
	}
	if len(types) == 0 {
		fmt.Fprintln(os.Stderr, "apitypes: 未解析到任何 type")
		os.Exit(1)
	}

	ts := render(types, order)
	if *out == "" {
		fmt.Print(ts)
		return
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "apitypes:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(ts), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "apitypes:", err)
		os.Exit(1)
	}
	fmt.Printf("apitypes: %d 类型 → %s\n", len(types), *out)
}

// parseFile 逐行解析 type 块（.api type 语法子集：单行字段 + 反引号标签；// 注释跳过）。
func parseFile(path string, types map[string]apiType, order *[]string) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()

	sc := bufio.NewScanner(f)
	var cur *apiType
	for sc.Scan() {
		line := sc.Text()
		trimmed := strings.TrimSpace(line)
		if trimmed == "" || strings.HasPrefix(trimmed, "//") {
			continue
		}
		if cur == nil {
			if m := typeDeclRe.FindStringSubmatch(line); m != nil {
				cur = &apiType{Name: m[1]}
			}
			continue
		}
		if strings.HasPrefix(trimmed, "}") {
			types[cur.Name] = *cur
			*order = append(*order, cur.Name)
			cur = nil
			continue
		}
		if m := typeRe.FindStringSubmatch(line); m != nil {
			tag := m[4]
			typ := m[3]
			if m[2] != "" { // []T
				typ = "[]" + typ
			}
			cur.Fields = append(cur.Fields, field{
				Name:     m[1],
				Type:     typ,
				Optional: strings.Contains(tag, ",optional") || strings.Contains(tag, ",default="),
			})
		}
	}
	return sc.Err()
}

// tsScalar .api 标量 → TS；自定义类型原样引用。
func tsScalar(t string) string {
	switch t {
	case "string":
		return "string"
	case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16",
		"uint32", "uint64", "float", "float32", "float64", "double":
		return "number"
	case "bool":
		return "boolean"
	default:
		return t
	}
}

// tsTypeFull 展开 []T。
func tsTypeFull(t string) string {
	if strings.HasPrefix(t, "[]") {
		return tsTypeFull(strings.TrimPrefix(t, "[]")) + "[]"
	}
	return tsScalar(t)
}

func render(types map[string]apiType, order []string) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/apitypes from .api contract. DO NOT EDIT.\n")
	b.WriteString("// 生成物入库（CI diff 阻断，02 §12.5）；改契约 → 重生成 → diff 干净。\n\n")

	names := append([]string(nil), order...)
	sort.Strings(names)
	for _, name := range names {
		t := types[name]
		fmt.Fprintf(&b, "export interface %s {\n", name)
		for _, fd := range t.Fields {
			opt := ""
			if fd.Optional {
				opt = "?"
			}
			fmt.Fprintf(&b, "\t%s%s: %s;\n", toSnake(fd.Name), opt, tsTypeFull(fd.Type))
		}
		b.WriteString("}\n\n")
	}
	return b.String()
}

// toSnake 字段名 → JSON 名（与 goctl json tag 生成一致）：大写字母前插下划线
// （仅当前一字符为小写/数字），整体小写。MenuID→menu_id、RoleIDs→role_ids、UID→uid。
func toSnake(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c >= 'A' && c <= 'Z' {
			if i > 0 {
				prev := s[i-1]
				if (prev >= 'a' && prev <= 'z') || (prev >= '0' && prev <= '9') {
					b.WriteByte('_')
				}
			}
			b.WriteByte(c - 'A' + 'a')
		} else {
			b.WriteByte(c)
		}
	}
	return b.String()
}
